const profileScripts = ['// Generated by npm run build. Edit the profile sources instead.'];
const definitions = [];
for (const file of (await readdir('profiles')).filter(file => file.endsWith('.json')).sort()) {
  definitions.push(JSON.parse(await readFile(`profiles/${file}`, 'utf8')));
}
for (const definition of orderProfiles(definitions)) {
  // Register frozen NAF revisions first so an unqualified ID selects
  // the current revision in both the standalone and combined scripts.
  const revisions = [definition];
  if (definition.id === 'naf41-uaf') {
    const archive = 'profiles/naf41/revisions';
    const filenames = (await readdir(archive)).filter(file => file.endsWith('.json'))
      .sort((a, b) => a.localeCompare(b, 'en', {numeric:true}));
    const frozen = await Promise.all(filenames.map(async file => JSON.parse(await readFile(`${archive}/${file}`, 'utf8'))));
    revisions.unshift(...frozen);
  }
  const script = revisions.map(revision => {
    registerProfile(definition.id, revision);
    return `arch.registerProfile(${JSON.stringify(definition.id)}, ${JSON.stringify(revision)});`;
  }).join('\n');
  profileScripts.push(script);
  await writeFile(`profiles/${definition.id}.js`, `// Generated by npm run build. Load base profile first when extends is used.\n${script}\n`);
}
await writeFile('profiles/profiles.js', profileScripts.join('\n') + '\n');
