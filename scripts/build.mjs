import { build } from 'esbuild';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { buildIconPacks } from './iconpacks.mjs';
import { registerProfile } from '../src/profiles.js';
import { buildUafProfiles } from './build-uaf.mjs';
import { orderProfiles } from './profile-order.mjs';

await mkdir('demo', { recursive: true });
await buildIconPacks();
await buildUafProfiles();
const profileScripts = ['// Generated by npm run build. Edit profiles/*.json instead.'];
const definitions = [];
for (const file of (await readdir('profiles')).filter(file => file.endsWith('.json')).sort()) {
  definitions.push(JSON.parse(await readFile(`profiles/${file}`, 'utf8')));
}
for (const definition of orderProfiles(definitions)) {
  registerProfile(definition.id, definition);
  const script = `arch.registerProfile(${JSON.stringify(definition.id)}, ${JSON.stringify(definition)});`;
  profileScripts.push(script);
  await writeFile(`profiles/${definition.id}.js`, `// Generated by npm run build. Load base profile first when extends is used.\n${script}\n`);
}
await writeFile('profiles/profiles.js', profileScripts.join('\n') + '\n');
const examples = [];
for (const [id, title, subtitle] of [
  ['platform', 'Customer platform', 'Systems, services & boundaries'],
  ['manual', 'Event-driven checkout', 'Precise placement & routing'],
  ['capabilities', 'Strategy to delivery', 'Capabilities & architecture layers'],
  ['iconpacks', 'Three icon libraries', 'Bootstrap, Lucide & Tabler'],
  ['profiles', 'Your own framework', 'Inline types, attributes & rules'],
  ['external-profile', 'Reusable JSON profile', 'One profile, many models'],
  ['uaf', 'NAF · UAF architecture', 'Capabilities to implementation'],
  ['diagrams', 'Seven diagram renderers', 'Behavior, matrices, maps & details'],
  ['minimal', 'Start from scratch', 'A small model to make your own'],
]) examples.push({ id, title, subtitle, source: await readFile(`examples/${id}.arch`, 'utf8') });
await writeFile('demo/examples.js', `// Generated by npm run build. Edit examples/*.arch instead.\nwindow.ARCH_EXAMPLES = ${JSON.stringify(examples, null, 2)};\n`);
const common = { entryPoints: ['src/arch.js'], bundle: true, format: 'iife', globalName: 'arch', target: ['es2020'], legalComments: 'none', charset: 'utf8' };
await build({ ...common, outfile: 'arch.js' });
await build({ ...common, minify: true, outfile: 'arch.min.js' });
console.log('Built arch.js, arch.min.js and demo/examples.js');
